# The box's parts (DESIGN D25 revision 3, 2.2 and 10 step 1; user/box.c): every command's own object, built as for the
# separate program, copied to BUILD/box/NAME.o with its main renamed to NAME__main, and the dispatcher's table
# BUILD/boxtab.h. A command object may define no global but main (each command's own names are static): the script
# refuses one that does, since two commands' globals would then clash or one would silently take the other's.
# usage: mkbox.sh BUILD "NAME ..." "ALIAS:NAME ..."
set -e
B="$1"; NAMES="$2"; ALIASES="$3"
: "${TOOLPREFIX:=m68k-elf-}"
mkdir -p "$B/box"
tab="$B/boxtab.h.tmp.$$"
trap 'rm -f "$tab"' EXIT
{
    echo "/* generated by tools/mkbox.sh: the box's commands (BOX) and second names (ALIAS) */"
    echo "#define BOX_TABLE \\"
} > "$tab"
for n in $NAMES; do
    [ -f "$B/$n.uo" ] || { echo "mkbox.sh: $B/$n.uo is missing" >&2; exit 1; }
    case $n in *[!a-z0-9_]*) echo "mkbox.sh: '$n' is not a name the table can hold" >&2; exit 1;; esac
    other=$("${TOOLPREFIX}nm" --defined-only -g "$B/$n.uo" | awk '$3 != "main" { print $3 }')
    [ -z "$other" ] || { echo "mkbox.sh: $n defines globals besides main ($other): make them static" >&2; exit 1; }
    "${TOOLPREFIX}nm" --defined-only -g "$B/$n.uo" | awk '$3 == "main" { f = 1 } END { exit !f }' ||
        { echo "mkbox.sh: $n.uo has no main" >&2; exit 1; }
    "${TOOLPREFIX}objcopy" --redefine-sym "main=${n}__main" "$B/$n.uo" "$B/box/$n.o"
    echo "    BOX($n) \\" >> "$tab"
done
for a in $ALIASES; do
    s=${a%%:*}; n=${a#*:}
    case " $NAMES " in *" $n "*) ;; *) echo "mkbox.sh: alias $s names $n, which is not in the box" >&2; exit 1;; esac
    case " $NAMES " in *" $s "*) echo "mkbox.sh: alias $s is a command of its own" >&2; exit 1;; esac
    echo "    ALIAS(\"$s\", $n) \\" >> "$tab"
done
echo "" >> "$tab"
# only a changed table is written, so the dispatcher is not rebuilt for nothing
cmp -s "$tab" "$B/boxtab.h" || mv "$tab" "$B/boxtab.h"
