# The C library's Zenix constants (DESIGN D27 section 5), generated, never typed twice: every name below is read from
# the kernel's headers (kernel/kernel.h, kernel/fsproto.h, kernel/netproto.h's socket numbers; the signals the kernel
# never raises itself and poll's bits from user/usys.h, the programs' copy of the same frozen numbers) and written as
# ZX_NAME into OUT, which the port's headers
# (libc/zenix/include) turn into the C names. tools/libc-host-test.sh checks the result against the kernel.
#   tools/libc-consts.sh OUT
cd "$(dirname "$0")/.." || exit 1
OUT=$1
NAMES="O_RDONLY O_WRONLY O_RDWR O_CREAT O_TRUNC O_APPEND O_NONBLOCK O_EXCL
 SIGHUP SIGINT SIGQUIT SIGILL SIGTRAP SIGABRT SIGBUS SIGFPE SIGKILL SIGUSR1 SIGSEGV SIGUSR2 SIGPIPE SIGALRM SIGTERM
 SIGCHLD SIGCONT SIGSTOP SIGTSTP SIGTTIN SIGTTOU SIGWINCH NSIG SIG_BLOCK SIG_UNBLOCK SIG_SETMASK SA_RESTART
 FS_UTIME_NOW S_IFMT S_IFDIR S_IFREG S_IFLNK S_IFSOCK NFD ENVMAX
 POLLIN POLLPRI POLLOUT POLLERR POLLHUP POLLNVAL POLLPORT
 AF_INET AF_UNSPEC SOCK_STREAM SOCK_DGRAM SOCK_RAW SOCK_NONBLOCK SOCK_CLOEXEC SOL_SOCKET SO_ERROR SO_RCVTIMEO
 SO_SNDTIMEO SO_REUSEADDR SO_TYPE SO_BROADCAST SO_SNDBUF SO_RCVBUF SO_KEEPALIVE SO_LINGER MSG_PEEK MSG_DONTWAIT
 MSG_NOSIGNAL FIONREAD FIONBIO IPPROTO_IP IPPROTO_ICMP IPPROTO_TCP IPPROTO_UDP TCP_NODELAY SHUT_RD SHUT_WR SHUT_RDWR"
{
    echo "/* generated by tools/libc-consts.sh from the kernel's headers: do not edit */"
    echo "#pragma once"
    for n in $NAMES; do
        v=""
        for h in kernel/kernel.h kernel/fsproto.h kernel/ext2.h kernel/netproto.h user/usys.h; do
            v=$(sed -n "s/^#define[ \t]\+$n[ \t]\+\(0x[0-9a-fA-F]\+[uU]\?\|[0-9]\+\)\b.*/\1/p" $h | head -1)
            [ -n "$v" ] && break
        done
        [ -n "$v" ] || { echo "libc-consts: $n not found in the kernel's headers" >&2; exit 1; }
        echo "#define ZX_$n $v"
    done
} > "$OUT.tmp" && mv "$OUT.tmp" "$OUT"
